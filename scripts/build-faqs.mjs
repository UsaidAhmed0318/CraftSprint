// Collects every tool's FAQ (the faq={[...]} given to ToolShell) into data/toolFaqs.generated.ts,
// so CraftSprint AI can answer from the same FAQs visitors see. Runs automatically before each build.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const registry = readFileSync(resolve(root, 'lib/toolRegistry.tsx'), 'utf8');
const entries = [...registry.matchAll(/'([a-z0-9-]+)':\s*dynamic\(\s*\(\)\s*=>\s*import\('@\/([^']+)'\)\.then\(m\s*=>\s*m\.(\w+)\)/g)];
const files = new Map();
const read = p => {
  if (!files.has(p)) {
    for (const ext of ['.tsx', '.ts']) {
      try {
        files.set(p, readFileSync(resolve(root, p + ext), 'utf8'));
        break;
      } catch {}
    }
  }
  return files.get(p) || '';
};
const unq = s => s.replace(/\\(['"`\\])/g, '$1').replace(/\s+/g, ' ').trim();
const STR = `('(?:\\\\.|[^'\\\\])*'|"(?:\\\\.|[^"\\\\])*"|\`(?:\\\\.|[^\`\\\\])*\`)`;
const pair = new RegExp(`q:\\s*${STR}\\s*,\\s*a:\\s*${STR}`, 'g');
const out = {};
for (const [, slug, path, name] of entries) {
  const src = read(path);
  const start = src.search(new RegExp(`export function ${name}\\b`));
  if (start < 0) continue;
  const next = src.slice(start + 10).search(/\nexport function /);
  const body = next < 0 ? src.slice(start) : src.slice(start, start + 10 + next);
  const i = body.indexOf('faq={[');
  if (i < 0) continue;
  const j = body.indexOf(']}', i);
  const block = body.slice(i, j);
  const faqs = [...block.matchAll(pair)].map(m => ({ q: unq(m[1].slice(1, -1)), a: unq(m[2].slice(1, -1)) }));
  if (faqs.length) out[slug] = faqs;
}
const text =
  '// AUTO-GENERATED by scripts/build-faqs.mjs from the FAQs on each tool page. Do not edit by hand.\n' +
  'export const toolFaqs: Record<string, { q: string; a: string }[]> = ' +
  JSON.stringify(out, null, 2) +
  ';\n';
writeFileSync(resolve(root, 'data/toolFaqs.generated.ts'), text);
console.log(`FAQs collected for ${Object.keys(out).length} tools (${Object.values(out).flat().length} questions).`);

export function QrCodeScanner() {
  const [result, setResult] = useState('');
  const [error, setError] = useState('');
  const onFile = (f: File) => {
    const img = new window.Image();
    img.onload = () => {
      const canvas = document.createElement('canvas');
      canvas.width = img.naturalWidth;
      canvas.height = img.naturalHeight;
      const ctx = canvas.getContext('2d')!;
      ctx.drawImage(img, 0, 0);
      const data = ctx.getImageData(0, 0, canvas.width, canvas.height);
      const code = jsQR(data.data, data.width, data.height);
      if (code) {
        setResult(code.data);
        setError('');
      } else {
        setError('No QR code found in this image.');
        setResult('');
      }
    };
    img.src = URL.createObjectURL(f);
  };
  const copy = () => navigator.clipboard?.writeText(result);
  return (
    <ToolShell
      title="QR code scanner"
      description="Upload an image containing a QR code to instantly decode its content, entirely in your browser."
      faq={[{ q: 'Is my image uploaded?', a: 'No, decoding happens locally using canvas pixel data.' }]}
    >
      <Dropzone onFile={onFile} />
      {error && <div className="notice error">{error}</div>}
      {result && (
        <div className="result">
          <span style={{ wordBreak: 'break-all' }}>{result}</span>
          <button className="btn btnDark" onClick={copy}>
            Copy
          </button>
        </div>
      )}
    </ToolShell>
  );
}

